// Multiple Object

// We can create a multiple object a one class

public class Banyak {
    int nomor = 23489;

    public static void main(String[] args) {
        Banyak lomba = new Banyak();
        Banyak lombayak = new Banyak();

        System.out.println(lomba.nomor);
        System.out.println(lombayak.nomor);
    }
}
